#define SUSAMUNE_GHOST_SHADOW_MASTER_OFFSET       0x00000000u
#define SUSAMUNE_GHOST_SHADOW_MASTER_SIZE         0x00010000u
#define SUSAMUNE_GHOST_PIANTA_MASTER_OFFSET       0x00010000u
#define SUSAMUNE_GHOST_PIANTA_MASTER_SIZE         0x00012000u
#define SUSAMUNE_GHOST_ASSET_VAULT_SIZE           0x00022000u
#define SUSAMUNE_GHOST_ASSET_VAULT_PHYS_BASE \
    (SUSAMUNE_MEM2_MODBIN_PHYS_BASE + SUSAMUNE_GHOST_ASSET_VAULT_OFFSET)
#define SUSAMUNE_GHOST_ASSET_VAULT_PPC_BASE \
    (SUSAMUNE_MEM2_MODBIN_PPC_BASE + SUSAMUNE_GHOST_ASSET_VAULT_OFFSET)

