#define SUSAMUNE_CONSOLE_GHOST_TRANSFER_PPC_BASE 0x91880000u

// patch.bin / patch.txt handoff: the loader writes through the cached PPC
// alias and the ARM kernel consumes the same bytes through the physical alias.
#define NIN_MEM2_FILE_PATCH_PHYS_BASE        0x11900000u
#define NIN_MEM2_FILE_PATCH_PPC_BASE         0x91900000u
#define NIN_MEM2_FILE_PATCH_SIZE             0x0057F000u

// mod_<region>.bin staging (struct SusamuneModHeader, mod_bin.h). The PPC
// loader reads the file for the detected disc here before booting the kernel;
// PatchSusamune() copies the code out into MEM1. PatchGame can consume this
// staging prefix again after an in-session reset, so it remains immutable.
//
// It shares the file-patch buffer's lifetime -- both are loader-to-kernel
// handoffs consumed at PatchGame time -- so it is carved off that buffer's tail
// rather than given memory of its own: 516 KiB out of six MiB, and the game
// never ships a patch.bin anyway. Deliberately NOT taken out of the snapshot
// window, whose payload can legitimately grow to fill its reservation.
#define SUSAMUNE_MEM2_MODBIN_PHYS_BASE       0x11E7F000u
#define SUSAMUNE_MEM2_MODBIN_PPC_BASE        0x91E7F000u
#define SUSAMUNE_MEM2_MODBIN_SIZE            0x00081000u

// PatchGame can consume the staged mod again after an in-session reset. The
// file may use the complete prefix before the immutable model-asset vault.
#define SUSAMUNE_MOD_STAGED_FILE_MAX_SIZE         0x0005F000u

// PatchSusamune consumes the complete mod staging file before the kernel
// publishes immutable retail model assets into its now-dead tail.
